// ─────────────────────────────────────────────────────────────
// PWA: Service worker strategy (Workbox).
//
//   app shell + JS chunks:   stale-while-revalidate, precache manifest
//   font catalog / assets:   cache-first (immutable, hashed URLs)
//   sync endpoints:          network-only (ops have their own outbox)
//   export workers:          not cached; large exports abort gracefully
//                            offline with a queued-on-reconnect task
//
// Background sync API for the outbox flush where supported; periodic
// polling fallback. Update flow: new SW activates on idle (no version
// reload nagging mid-edit), banner offers refresh when idle >5s.
// ─────────────────────────────────────────────────────────────

// ============ SW REGISTRATION ============

/**
 * Registers the service worker.
 * Called on app load — no-op in development.
 *
 * The SW precaches the app shell (HTML + JS chunks + CSS) via a
 * Workbox-generated manifest. On subsequent loads, the SW serves
 * the cached shell immediately (stale-while-revalidate).
 */
export async function registerServiceWorker(): Promise<void> {
  if (!("serviceWorker" in navigator)) return;
  if (process.env.NODE_ENV !== "production") return;

  try {
    const registration = await navigator.serviceWorker.register("/sw.js", {
      scope: "/",
    });

    // Check for updates on load.
    registration.addEventListener("updatefound", () => {
      const newWorker = registration.installing;
      if (!newWorker) return;

      newWorker.addEventListener("statechange", () => {
        if (newWorker.state === "installed" && navigator.serviceWorker.controller) {
          // New SW available — show banner when user is idle (>5s).
          scheduleUpdateBanner();
        }
      });
    });
  } catch {
    // SW registration failed — app still works (network-only fallback).
  }
}

// ============ UPDATE BANNER ============

let updateBannerTimer: ReturnType<typeof setTimeout> | null = null;

function scheduleUpdateBanner(): void {
  if (updateBannerTimer) return;

  // Wait 5s of idle before showing the update banner.
  updateBannerTimer = setTimeout(() => {
    showUpdateBanner();
  }, 5000);
}

function showUpdateBanner(): void {
  // Dispatch a custom event — the app shell listens + renders the banner.
  window.dispatchEvent(new CustomEvent("sw-update-available"));
}

/**
 * Triggers the service worker update (called when the user clicks "Refresh").
 */
export async function applyServiceWorkerUpdate(): Promise<void> {
  const registration = await navigator.serviceWorker.getRegistration();
  if (!registration?.waiting) return;

  // Tell the waiting SW to activate.
  registration.waiting.postMessage({ type: "SKIP_WAITING" });

  // Reload when the new SW takes control.
  navigator.serviceWorker.addEventListener("controllerchange", () => {
    window.location.reload();
  });
}

// ============ BACKGROUND SYNC (outbox flush) ============

/**
 * Registers a background sync task for the outbox flush.
 *
 * If the browser supports the Background Sync API, the outbox will
 * be flushed even if the user closes the tab — the SW wakes up
 * when network is available + drains the outbox.
 *
 * Fallback: periodic polling (setInterval) while the tab is open.
 */
type BackgroundSyncRegistration = ServiceWorkerRegistration & {
  sync?: { register(tag: string): Promise<void> };
};

export async function registerBackgroundSync(): Promise<void> {
  if (!("serviceWorker" in navigator)) return;
  if (!("SyncManager" in window)) return; // not supported

  try {
    const registration = await navigator.serviceWorker.ready as BackgroundSyncRegistration;
    if (!registration.sync) return;
    await registration.sync.register("outbox-flush");
  } catch {
    // Background sync not supported — fall back to polling.
  }
}

// ============ OFFLINE DETECTION ============

let isOnline = typeof navigator !== "undefined" ? navigator.onLine : true;

export function onOnlineStatusChange(handler: (online: boolean) => void): () => void {
  const onlineListener = () => {
    isOnline = true;
    handler(true);
  };
  const offlineListener = () => {
    isOnline = false;
    handler(false);
  };

  window.addEventListener("online", onlineListener);
  window.addEventListener("offline", offlineListener);

  return () => {
    window.removeEventListener("online", onlineListener);
    window.removeEventListener("offline", offlineListener);
  };
}

export function getIsOnline(): boolean {
  return isOnline;
}

// ============ SERVICE WORKER SOURCE (inline for dev) ============

/**
 * The service worker source code, as a string.
 * In production, this is generated by Workbox via the build pipeline.
 * In development, it's inlined for convenience.
 *
 * Strategy:
 *   app shell + JS chunks:   stale-while-revalidate
 *   font catalog / assets:   cache-first (immutable, hashed URLs)
 *   sync endpoints:          network-only (ops have their own outbox)
 *   export workers:          not cached
 */
export const SW_SOURCE = `
// Service Worker — generated by @supa/app-shell.
// DO NOT EDIT — this is generated from the build manifest.

const CACHE_VERSION = "v1";
const PRECACHE = "precache-" + CACHE_VERSION;
const RUNTIME = "runtime-" + CACHE_VERSION;

// Precache manifest (injected by the build).
const PRECACHE_URLS = [
  "/",
  "/index.html",
  // JS chunks + CSS are added by the build manifest.
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(PRECACHE).then((cache) => cache.addAll(PRECACHE_URLS))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys
          .filter((key) => key !== PRECACHE && key !== RUNTIME)
          .map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // Sync endpoints: network-only (ops have their own outbox).
  if (url.pathname.startsWith("/api/sync") || url.pathname.startsWith("/api/work/share")) {
    return; // let it go to the network
  }

  // Export workers: not cached.
  if (url.pathname.startsWith("/api/work/export")) {
    return;
  }

  // Font catalog + assets: cache-first (immutable, hashed URLs).
  if (url.pathname.match(/\\.(woff2|woff|ttf|otf)$/) ||
      url.pathname.startsWith("/assets/")) {
    event.respondWith(
      caches.match(request).then((cached) => {
        return cached || fetch(request).then((response) => {
          const clone = response.clone();
          caches.open(RUNTIME).then((cache) => cache.put(request, clone));
          return response;
        });
      })
    );
    return;
  }

  // App shell + JS chunks: stale-while-revalidate.
  if (request.mode === "navigate" ||
      url.pathname.startsWith("/_next/") ||
      url.pathname.match(/\\.(js|css)$/)) {
    event.respondWith(
      caches.match(request).then((cached) => {
        const fetchPromise = fetch(request).then((response) => {
          const clone = response.clone();
          caches.open(RUNTIME).then((cache) => cache.put(request, clone));
          return response;
        });
        return cached || fetchPromise;
      })
    );
    return;
  }
});

// Background sync: flush outbox on reconnect.
self.addEventListener("sync", (event) => {
  if (event.tag === "outbox-flush") {
    event.waitUntil(
      self.clients.matchAll().then((clients) => {
        clients.forEach((client) => {
          client.postMessage({ type: "FLUSH_OUTBOX" });
        });
      })
    );
  }
});

// Skip waiting (for update flow).
self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});
`;
