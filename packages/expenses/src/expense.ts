/**
 * @supa/expenses/expense
 * ----------------------------------------------------------------
 * Expense: { id, wsId, profileId, merchant, amount: Money (native
 *   currency — an ₦ receipt stays ₦ even in a USD workspace),
 *   date, category (data, per-workspace, seeded with sensible
 *   defaults: transport, supplies, rent, utilities, salary,
 *   data/airtime, professional — the Nigerian/Moroccan SME
 *   category reality, not a US accounting textbook), taxDeductible:
 *   boolean + taxRate at time of entry (recorded, not looked-up-
 *   later — the tax report must be reproducible from stored facts),
 *   receiptRef?, recurringRule?, mileage?, status: 'draft'|'recorded'
 *   |'approved'|'rejected'|'reimbursed', createdBy, paidBy:
 *   'cash'|'bank'|'card'|'provider' }
 *
 * Same discipline as invoices: status is a state machine with
 *   transitions as facts; 'recorded' is the durable state, 'draft'
 *   is an unfinished capture that costs nothing. Reimbursable
 *   expenses track paidBy + reimbursedAt as facts — the owner's
 *   "what do I owe myself/staff" is a query.
 *
 * Multi-currency: identical rules to invoicing — native amount
 *   is truth, base-currency conversion happens in report queries
 *   at recorded rates, originals always visible. One shared
 *   conversion module; zero per-feature FX logic anywhere.
 * ----------------------------------------------------------------
 */

import type { WorkspaceId } from "@supa/workspace-core/workspace";
import type { Money } from "@supa/money/money";

// ───────────────────────────────────────────────
// Expense status — state machine with transitions as facts
// ───────────────────────────────────────────────

export type ExpenseStatus = "draft" | "recorded" | "approved" | "rejected" | "reimbursed";

/**
 * Status transitions:
 *   draft    → recorded (capture complete — durable state)
 *   draft    → draft   (still editing — costs nothing)
 *   recorded → approved (team approval flow — solo workspaces skip)
 *   recorded → rejected (team approval flow)
 *   approved → reimbursed (payment linked)
 *   rejected → recorded (re-submit after fixing)
 *
 * 'recorded' is the durable state for solo workspaces. The
 * approval flow only applies to workspaces with team roles beyond
 * owner (see approval.ts).
 */
const ALLOWED_TRANSITIONS: Record<ExpenseStatus, readonly ExpenseStatus[]> = {
  draft: ["recorded", "draft"],
  recorded: ["approved", "rejected"],
  approved: ["reimbursed"],
  rejected: ["recorded"],
  reimbursed: [],
};

export function canTransition(from: ExpenseStatus, to: ExpenseStatus): boolean {
  return ALLOWED_TRANSITIONS[from].includes(to);
}

export class InvalidExpenseTransitionError extends Error {
  constructor(readonly from: ExpenseStatus, readonly to: ExpenseStatus) {
    super(`invalid expense status transition: ${from} → ${to}`);
    this.name = "InvalidExpenseTransitionError";
  }
}

// ───────────────────────────────────────────────
// Categories — per-workspace data, SME reality
// ───────────────────────────────────────────────

/**
 * Default expense categories. Seeded with the Nigerian/Moroccan SME
 * category reality, not a US accounting textbook:
 *
 *   transport     — fuel, taxi, okada
 *   supplies      — office supplies, materials
 *   rent          — office/shop rent
 *   utilities     — electricity, water, internet
 *   salary        — staff salary
 *   data/airtime  — mobile data, airtime
 *   professional  — legal, accounting, consulting
 *
 * Per-workspace customizable — workspaces can add/rename/reorder.
 */
export const DEFAULT_CATEGORIES = [
  "transport",
  "supplies",
  "rent",
  "utilities",
  "salary",
  "data/airtime",
  "professional",
] as const;

export type DefaultCategory = (typeof DEFAULT_CATEGORIES)[number];

// ───────────────────────────────────────────────
// Payment method
// ───────────────────────────────────────────────

export type PaidBy = "cash" | "bank" | "card" | "provider";

// ───────────────────────────────────────────────
// Expense entity
// ───────────────────────────────────────────────

/**
 * The expense record. Native currency is truth — an ₦ receipt stays
 * ₦ even in a USD workspace. Conversion to base happens only in
 * report queries, at recorded rates, originals always visible.
 *
 *   taxDeductible + taxRate — the taxRate is RECORDED at time of
 *   entry (not looked-up-later). The tax report must be
 *   reproducible from stored facts — if the rate changes next year,
 *   this expense still shows the rate that was in effect when it
 *   was incurred.
 *
 *   receiptRef — content-addressed hash of the receipt image (see
 *   receipts.ts). Multiple expenses from the same merchant may share
 *   receipt photos; the content-addressed store dedupes.
 *
 *   recurringRuleId — if this expense was generated by a recurring
 *   rule (see recurring.ts), the rule id + the period key for
 *   idempotency.
 *
 *   mileage — if this expense is a mileage expense (see mileage.ts),
 *   the distance + rate recorded at entry time.
 */
export interface Expense {
  readonly id: string;
  readonly wsId: WorkspaceId;
  readonly profileId: string;
  readonly merchant: string;
  /** Native amount + currency (₦ receipt = ₦ Money, even in USD workspace). */
  readonly amount: Money;
  /** Date incurred (ms epoch). */
  readonly date: number;
  /** Category (per-workspace data, defaults from DEFAULT_CATEGORIES). */
  readonly category: string;
  /** Whether this expense is tax-deductible. */
  readonly taxDeductible: boolean;
  /** Tax rate at time of entry (decimal string, e.g. "0.075" for 7.5% VAT). Recorded, not looked-up-later. */
  readonly taxRate: string | null;
  /** Content-addressed receipt image hash (see receipts.ts). */
  readonly receiptRef: string | null;
  /** Recurring rule id (if generated by a recurring rule). */
  readonly recurringRuleId: string | null;
  /** Period key for recurring idempotency (e.g. "2024-03" for March rent). */
  readonly recurringPeriodKey: string | null;
  /** Mileage details (if this is a mileage expense). */
  readonly mileage: MileageDetail | null;
  readonly status: ExpenseStatus;
  readonly createdBy: string;
  readonly paidBy: PaidBy;
  /** Reimbursement timestamp (null unless status=reimbursed). */
  readonly reimbursedAt: number | null;
  readonly createdAt: number;
  readonly updatedAt: number;
}

export interface MileageDetail {
  /** Trip distance in km. */
  readonly distanceKm: number;
  /** Rate per km at entry time (in workspace base currency, as decimal string). */
  readonly ratePerKm: string;
  /** Origin (optional — GPS capture is convenience, not required). */
  readonly origin: string | null;
  /** Destination (optional). */
  readonly destination: string | null;
}

