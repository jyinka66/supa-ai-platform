export interface CreateExpenseInput {
  readonly id: string;
  readonly wsId: WorkspaceId;
  readonly profileId: string;
  readonly merchant: string;
  readonly amount: Money;
  readonly date: number;
  readonly category: string;
  readonly taxDeductible: boolean;
  readonly taxRate: string | null;
  readonly receiptRef: string | null;
  readonly recurringRuleId: string | null;
  readonly recurringPeriodKey: string | null;
  readonly mileage: MileageDetail | null;
  readonly createdBy: string;
  readonly paidBy: PaidBy;
}

/**
 * Create a draft expense. Drafts cost nothing — an unfinished
 * capture (e.g. receipt photo taken but fields not yet filled)
 * doesn't consume a number or create a fact. Status='draft' until
 * the capture is complete + the user confirms.
 */
export function createDraft(input: CreateExpenseInput, now: number = Date.now()): Expense {
  return {
    id: input.id,
    wsId: input.wsId,
    profileId: input.profileId,
    merchant: input.merchant.trim(),
    amount: input.amount,
    date: input.date,
    category: input.category,
    taxDeductible: input.taxDeductible,
    taxRate: input.taxRate,
    receiptRef: input.receiptRef,
    recurringRuleId: input.recurringRuleId,
    recurringPeriodKey: input.recurringPeriodKey,
    mileage: input.mileage,
    status: "draft",
    createdBy: input.createdBy,
    paidBy: input.paidBy,
    reimbursedAt: null,
    createdAt: now,
    updatedAt: now,
  };
}

/**
 * Record a draft expense (draft → recorded). The durable state —
 * the expense is now a fact in the system, queryable + reportable.
 */
export function record(expense: Expense, now: number = Date.now()): Expense {
  if (!canTransition(expense.status, "recorded")) {
    throw new InvalidExpenseTransitionError(expense.status, "recorded");
  }
  return { ...expense, status: "recorded", updatedAt: now };
}

/**
 * Approve an expense (recorded → approved). Team approval flow only.
 */
export function approve(expense: Expense, now: number = Date.now()): Expense {
  if (!canTransition(expense.status, "approved")) {
    throw new InvalidExpenseTransitionError(expense.status, "approved");
  }
  return { ...expense, status: "approved", updatedAt: now };
}

/**
 * Reject an expense (recorded → rejected). Team approval flow only.
 */
export function reject(expense: Expense, now: number = Date.now()): Expense {
  if (!canTransition(expense.status, "rejected")) {
    throw new InvalidExpenseTransitionError(expense.status, "rejected");
  }
  return { ...expense, status: "rejected", updatedAt: now };
}

/**
 * Mark an expense as reimbursed (approved → reimbursed). Links a
 * payment + sets reimbursedAt. The owner's "what do I owe myself/staff"
 * is a query over reimbursedAt (null = owed, non-null = paid).
 */
export function reimburse(expense: Expense, now: number = Date.now()): Expense {
  if (!canTransition(expense.status, "reimbursed")) {
    throw new InvalidExpenseTransitionError(expense.status, "reimbursed");
  }
  return { ...expense, status: "reimbursed", reimbursedAt: now, updatedAt: now };
}

/**
 * Re-submit a rejected expense (rejected → recorded). The user fixes
 * the issue + re-submits for approval.
 */
export function resubmit(expense: Expense, now: number = Date.now()): Expense {
  if (!canTransition(expense.status, "recorded")) {
    throw new InvalidExpenseTransitionError(expense.status, "recorded");
  }
  return { ...expense, status: "recorded", updatedAt: now };
}

/**
 * Update fields on a draft expense (still editing — costs nothing).
 */
export function updateDraft(
  expense: Expense,
  changes: Partial<Pick<Expense, "merchant" | "amount" | "date" | "category" | "taxDeductible" | "taxRate" | "receiptRef" | "mileage" | "paidBy">>,
  now: number = Date.now(),
): Expense {
  if (expense.status !== "draft") {
    throw new InvalidExpenseTransitionError(expense.status, "draft");
  }
  return {
    ...expense,
    ...(changes.merchant !== undefined ? { merchant: changes.merchant.trim() } : {}),
    ...(changes.amount !== undefined ? { amount: changes.amount } : {}),
    ...(changes.date !== undefined ? { date: changes.date } : {}),
    ...(changes.category !== undefined ? { category: changes.category } : {}),
    ...(changes.taxDeductible !== undefined ? { taxDeductible: changes.taxDeductible } : {}),
    ...(changes.taxRate !== undefined ? { taxRate: changes.taxRate } : {}),
    ...(changes.receiptRef !== undefined ? { receiptRef: changes.receiptRef } : {}),
    ...(changes.mileage !== undefined ? { mileage: changes.mileage } : {}),
    ...(changes.paidBy !== undefined ? { paidBy: changes.paidBy } : {}),
    updatedAt: now,
  };
}

// ───────────────────────────────────────────────
// Reimbursement query — "what do I owe myself/staff?"
// ───────────────────────────────────────────────

/**
 * Query reimbursable expenses. Returns expenses that are approved
 * (owed, not yet reimbursed) or reimbursed (paid). The owner's
 * "what do I owe" is the sum of approved-but-not-reimbursed.
 */
export interface ReimbursementSummary {
  /** Approved but not yet reimbursed (owed). */
  readonly owed: readonly Expense[];
  /** Reimbursed (paid). */
  readonly reimbursed: readonly Expense[];
  /** Total owed (sum of owed amounts, in mixed currencies — see computeReimbursementTotals). */
  readonly owedCount: number;
  readonly reimbursedCount: number;
}

export function queryReimbursements(expenses: ReadonlyArray<Expense>): ReimbursementSummary {
  const owed = expenses.filter((e) => e.status === "approved");
  const reimbursed = expenses.filter((e) => e.status === "reimbursed");
  return {
    owed,
    reimbursed,
    owedCount: owed.length,
    reimbursedCount: reimbursed.length,
  };
}

