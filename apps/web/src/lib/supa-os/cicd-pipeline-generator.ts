// CI/CD pipeline generator — produces the YAML config files that re-deploy
// the built app on every git push.
//
// The Phase 4 spec says: "Integrate automated CI/CD pipelines to deploy
// generated apps to Vercel, AWS, GCP, Supabase, or self-hosted Docker
// environments with a single click."
//
// The existing `oneClickDeploy()` in multi-cloud-deploy.ts produces a deploy
// target config + state machine for the INITIAL deploy. This module produces
// the YAML files that go INTO the app's repository so the app stays deployed
// going forward — every push to main triggers the pipeline.
//
// Supported CI providers (chosen by what the developer's repo uses):
//   - github_actions  → .github/workflows/deploy.yml
//   - gitlab_ci        → .gitlab-ci.yml
//   - circleci         → .circleci/config.yml
//
// Each provider has a generator function per deploy target. The generators
// are pure functions — they take the deploy target + app config + return a
// string. No file I/O (the route handler writes the file to the repo).

import type { CloudDeployTargetId } from "@/lib/supa-os/multi-cloud-deploy";

// ───────────────────────────────────────────────
// Types
// ───────────────────────────────────────────────

export type CiProvider = "github_actions" | "gitlab_ci" | "circleci";

export interface PipelineGeneratorInput {
  /** The deploy target — determines which deploy steps to emit. */
  target: CloudDeployTargetId;
  /** The CI provider — determines the YAML shape + file path. */
  provider: CiProvider;
  /** App name (used in job names + artifact names). */
  appName: string;
  /** Whether to run tests before deploying. */
  runTests: boolean;
  /** Whether to run lint before deploying. */
  runLint: boolean;
  /** Whether to require manual approval before production deploy. */
  requireManualApproval: boolean;
  /** Environment variables the pipeline needs (e.g. VERCEL_TOKEN, AWS_ACCESS_KEY_ID). */
  requiredSecrets: string[];
}

export interface GeneratedPipeline {
  /** The CI provider this pipeline is for. */
  provider: CiProvider;
  /** The file path inside the repo where this YAML should be written. */
  filePath: string;
  /** The YAML content. */
  content: string;
}

// ───────────────────────────────────────────────
// Top-level dispatcher.
// ───────────────────────────────────────────────

export function generatePipeline(input: PipelineGeneratorInput): GeneratedPipeline {
  switch (input.provider) {
    case "github_actions":
      return generateGitHubActions(input);
    case "gitlab_ci":
      return generateGitLabCi(input);
    case "circleci":
      return generateCircleCi(input);
    default:
      throw new Error(`Unknown CI provider: ${input.provider as string}`);
  }
}

// ───────────────────────────────────────────────
// GitHub Actions
// ───────────────────────────────────────────────

function generateGitHubActions(input: PipelineGeneratorInput): GeneratedPipeline {
  const { target, appName, runTests, runLint, requireManualApproval, requiredSecrets } = input;
  const secretsBlock = requiredSecrets.length > 0
    ? requiredSecrets.map((s) => `          ${s}: \${{ secrets.${s} }}`).join("\n")
    : "";

  const lines: string[] = [
    `# Auto-generated by Supa OS — CI/CD pipeline for ${appName} on ${target}.`,
    `# Re-deploys on every push to main.`,
    `name: Deploy`,
    ``,
    `on:`,
    `  push:`,
    `    branches: [main]`,
    `  workflow_dispatch:`,
    ``,
    `permissions:`,
    `  contents: read`,
    `  deployments: write`,
    ``,
    `concurrency:`,
    `  group: deploy-${target}`,
    `  cancel-in-progress: false`,
    ``,
    `jobs:`,
  ];

  // Build job.
  lines.push(`  build:`);
  lines.push(`    runs-on: ubuntu-latest`);
  lines.push(`    steps:`);
  lines.push(`      - uses: actions/checkout@v4`);
  lines.push(`      - uses: actions/setup-node@v4`);
  lines.push(`        with:`);
  lines.push(`          node-version: 20`);
  lines.push(`          cache: npm`);
  if (runLint) {
    lines.push(`      - name: Lint`);
    lines.push(`        run: npm run lint`);
  }
  if (runTests) {
    lines.push(`      - name: Test`);
    lines.push(`        run: npm test`);
  }
  lines.push(`      - name: Build`);
  lines.push(`        run: npm run build`);

  // Deploy job.
  const deployJobName = requireManualApproval ? `  deploy-staging` : `  deploy`;
  lines.push(``);
  lines.push(deployJobName + `:`);
  lines.push(`    needs: build`);
  lines.push(`    runs-on: ubuntu-latest`);
  if (requireManualApproval) {
    lines.push(`    environment:`);
    lines.push(`      name: staging`);
    lines.push(`      url: https://${appName}.example.com`);
  }
  lines.push(`    steps:`);
  lines.push(`      - uses: actions/checkout@v4`);
  lines.push(`      - uses: actions/setup-node@v4`);
  lines.push(`        with:`);
  lines.push(`          node-version: 20`);
  lines.push(`          cache: npm`);
  if (secretsBlock) {
    lines.push(`      - name: Configure secrets`);
    lines.push(`        env:`);
    lines.push(secretsBlock);
  }
  // Provider-specific deploy step.
  lines.push(...githubActionsDeploySteps(target, appName));

  // Production approval gate (if required).
  if (requireManualApproval) {
    lines.push(``);
    lines.push(`  deploy-production:`);
    lines.push(`    needs: deploy-staging`);
    lines.push(`    runs-on: ubuntu-latest`);
    lines.push(`    environment:`);
    lines.push(`      name: production`);
    lines.push(`      url: https://${appName}.production.example.com`);
    lines.push(`    steps:`);
    lines.push(`      - uses: actions/checkout@v4`);
    lines.push(`      - uses: actions/setup-node@v4`);
    lines.push(`        with:`);
    lines.push(`          node-version: 20`);
    lines.push(`          cache: npm`);
    if (secretsBlock) {
      lines.push(`      - name: Configure secrets`);
      lines.push(`        env:`);
      lines.push(secretsBlock);
    }
    lines.push(...githubActionsDeploySteps(target, appName));
  }

  return {
    provider: "github_actions",
    filePath: `.github/workflows/deploy.yml`,
    content: lines.join("\n") + "\n",
  };
}

function githubActionsDeploySteps(target: CloudDeployTargetId, appName: string): string[] {
  switch (target) {
    case "vercel":
      return [
        `      - name: Deploy to Vercel`,
        `        uses: amondnet/vercel-action@v25`,
        `        with:`,
        `          vercel-token: \${{ secrets.VERCEL_TOKEN }}`,
        `          vercel-org-id: \${{ secrets.VERCEL_ORG_ID }}`,
        `          vercel-project-id: \${{ secrets.VERCEL_PROJECT_ID }}`,
        `          vercel-args: '--prod'`,
      ];
    case "aws":
      return [
        `      - name: Configure AWS credentials`,
        `        uses: aws-actions/configure-aws-credentials@v4`,
        `        with:`,
        `          aws-access-key-id: \${{ secrets.AWS_ACCESS_KEY_ID }}`,
        `          aws-secret-access-key: \${{ secrets.AWS_SECRET_ACCESS_KEY }}`,
        `          aws-region: \${{ secrets.AWS_REGION }}`,
        `      - name: Build + push to ECR`,
        `        uses: aws-actions/amazon-ecr-build-and-push@v1`,
        `        with:`,
        `          image-tag: \${{ github.sha }}`,
        `      - name: Deploy to ECS Fargate`,
        `        run: aws ecs update-service --cluster ${appName}-cluster --service ${appName}-service --force-new-deployment`,
      ];
    case "gcp":
      return [
        `      - name: Authenticate to Google Cloud`,
        `        uses: google-github-actions/auth@v2`,
        `        with:`,
        `          credentials_json: \${{ secrets.GCP_SA_KEY }}`,
        `      - name: Deploy to Cloud Run`,
        `        uses: google-github-actions/deploy-cloudrun@v2`,
        `        with:`,
        `          service: ${appName}`,
        `          region: \${{ secrets.GCP_REGION }}`,
        `          image: gcr.io/\${{ secrets.GCP_PROJECT_ID }}/${appName}:\${{ github.sha }}`,
      ];
    case "supabase":
      return [
        `      - name: Install Supabase CLI`,
        `        run: npm install -g supabase`,
        `      - name: Push migrations`,
        `        run: supabase db push`,
        `        env:`,
        `          SUPABASE_ACCESS_TOKEN: \${{ secrets.SUPABASE_ACCESS_TOKEN }}`,
        `      - name: Deploy Edge Functions`,
        `        run: supabase functions deploy`,
        `        env:`,
        `          SUPABASE_ACCESS_TOKEN: \${{ secrets.SUPABASE_ACCESS_TOKEN }}`,
      ];
    case "self_hosted":
      return [
        `      - name: Build Docker image`,
        `        run: docker build -t ${appName}:\${{ github.sha }} .`,
        `      - name: Save image`,
        `        run: docker save ${appName}:\${{ github.sha }} | gzip > ${appName}.tar.gz`,
        `      - name: Copy to server`,
        `        uses: appleboy/scp-action@v0.1.7`,
        `        with:`,
        `          host: \${{ secrets.DEPLOY_HOST }}`,
        `          username: \${{ secrets.DEPLOY_USER }}`,
        `          key: \${{ secrets.DEPLOY_SSH_KEY }}`,
        `          source: ${appName}.tar.gz`,
        `          target: /tmp/`,
        `      - name: Restart service`,
        `        uses: appleboy/ssh-action@v1.0.3`,
        `        with:`,
        `          host: \${{ secrets.DEPLOY_HOST }}`,
        `          username: \${{ secrets.DEPLOY_USER }}`,
        `          key: \${{ secrets.DEPLOY_SSH_KEY }}`,
        `          script: docker load < /tmp/${appName}.tar.gz && docker-compose up -d`,
      ];
    default:
      return [`      - name: Deploy`, `        run: echo "TODO: deploy step for ${target}"`];
  }
}

// ───────────────────────────────────────────────
// GitLab CI
// ───────────────────────────────────────────────

function generateGitLabCi(input: PipelineGeneratorInput): GeneratedPipeline {
  const { target, appName, runTests, runLint, requireManualApproval, requiredSecrets } = input;
  const lines: string[] = [
    `# Auto-generated by Supa OS — CI/CD pipeline for ${appName} on ${target}.`,
    `image: node:20`,
    ``,
    `stages:`,
    `  - test`,
    `  - build`,
    `  - deploy`,
    ``,
  ];
  if (runLint) {
    lines.push(`lint:`);
    lines.push(`  stage: test`);
    lines.push(`  script: npm ci && npm run lint`);
    lines.push(`  rules:`);
    lines.push(`    - if: $CI_PIPELINE_SOURCE == "push"`);
    lines.push(``);
  }
  if (runTests) {
    lines.push(`test:`);
    lines.push(`  stage: test`);
    lines.push(`  script: npm ci && npm test`);
    lines.push(`  rules:`);
    lines.push(`    - if: $CI_PIPELINE_SOURCE == "push"`);
    lines.push(``);
  }
  lines.push(`build:`);
  lines.push(`  stage: build`);
  lines.push(`  script: npm ci && npm run build`);
  lines.push(`  artifacts:`);
  lines.push(`    paths:`);
  lines.push(`      - .next/`);
  lines.push(`      - dist/`);
  lines.push(`  rules:`);
  lines.push(`    - if: $CI_COMMIT_BRANCH == "main"`);
  lines.push(``);

  lines.push(`deploy:`);
  lines.push(`  stage: deploy`);
  lines.push(`  needs: [build]`);
  if (requireManualApproval) {
    lines.push(`  when: manual`);
  }
  lines.push(`  script:`);
  // Per-target deploy commands.
  const deployCmds = gitlabDeployCommands(target, appName);
  for (const cmd of deployCmds) lines.push(`    - ${cmd}`);
  if (requiredSecrets.length > 0) {
    lines.push(`  variables:`);
    for (const s of requiredSecrets) lines.push(`    ${s}: $${s}`);
  }
  return {
    provider: "gitlab_ci",
    filePath: `.gitlab-ci.yml`,
    content: lines.join("\n") + "\n",
  };
}

function gitlabDeployCommands(target: CloudDeployTargetId, appName: string): string[] {
  switch (target) {
    case "vercel":
      return [`npm i -g vercel`, `vercel --prod --yes --token=$VERCEL_TOKEN`];
    case "aws":
      return [`aws ecr get-login-password | docker login --username AWS --password-stdin $AWS_ACCOUNT_ID.dkr.ecr.$AWS_REGION.amazonaws.com`, `docker build -t ${appName} .`, `docker tag ${appName}:latest $AWS_ACCOUNT_ID.dkr.ecr.$AWS_REGION.amazonaws.com/${appName}:latest`, `docker push $AWS_ACCOUNT_ID.dkr.ecr.$AWS_REGION.amazonaws.com/${appName}:latest`, `aws ecs update-service --cluster ${appName}-cluster --service ${appName}-service --force-new-deployment`];
    case "gcp":
      return [`echo $GCP_SA_KEY | base64 -d > /tmp/key.json`, `gcloud auth activate-service-account --key-file=/tmp/key.json`, `gcloud run deploy ${appName} --source . --region $GCP_REGION --platform managed`];
    case "supabase":
      return [`npm i -g supabase`, `supabase db push`, `supabase functions deploy`];
    case "self_hosted":
      return [`docker build -t ${appName}:latest .`, `docker save ${appName}:latest | gzip > /tmp/${appName}.tar.gz`, `scp /tmp/${appName}.tar.gz $DEPLOY_USER@$DEPLOY_HOST:/tmp/`, `ssh $DEPLOY_USER@$DEPLOY_HOST "docker load < /tmp/${appName}.tar.gz && docker-compose up -d"`];
    default:
      return [`echo "TODO: deploy for ${target}"`];
  }
}

// ───────────────────────────────────────────────
// CircleCI
// ───────────────────────────────────────────────

function generateCircleCi(input: PipelineGeneratorInput): GeneratedPipeline {
  const { target, appName, runTests, runLint, requireManualApproval, requiredSecrets } = input;
  const lines: string[] = [
    `# Auto-generated by Supa OS — CI/CD pipeline for ${appName} on ${target}.`,
    `version: 2.1`,
    ``,
    `orbs:`,
    `  node: circleci/node@5.2.0`,
    ``,
    `jobs:`,
  ];
  if (runLint || runTests) {
    lines.push(`  test:`);
    lines.push(`    docker:`);
    lines.push(`      - image: cimg/node:20.10`);
    lines.push(`    steps:`);
    lines.push(`      - checkout`);
    lines.push(`      - node/install-packages`);
    if (runLint) lines.push(`      - run: npm run lint`);
    if (runTests) lines.push(`      - run: npm test`);
    lines.push(``);
  }
  lines.push(`  build:`);
  lines.push(`    docker:`);
  lines.push(`      - image: cimg/node:20.10`);
  lines.push(`    steps:`);
  lines.push(`      - checkout`);
  lines.push(`      - node/install-packages`);
  lines.push(`      - run: npm run build`);
  lines.push(`      - persist_to_workspace:`);
  lines.push(`          root: .`);
  lines.push(`          paths:`);
  lines.push(`            - .next/`);
  lines.push(`            - dist/`);
  lines.push(``);
  lines.push(`  deploy:`);
  lines.push(`    docker:`);
  lines.push(`      - image: cimg/node:20.10`);
  lines.push(`    steps:`);
  lines.push(`      - checkout`);
  lines.push(`      - attach_workspace:`);
  lines.push(`          at: .`);
  for (const s of requiredSecrets) lines.push(`      - run: echo "${s} is set" # \${${s}}`);
  // Per-target deploy commands (reuse the GitLab ones — they're plain shell).
  for (const cmd of gitlabDeployCommands(target, appName)) {
    lines.push(`      - run: ${cmd}`);
  }
  lines.push(``);
  lines.push(`workflows:`);
  lines.push(`  build-and-deploy:`);
  lines.push(`    jobs:`);
  if (runLint || runTests) lines.push(`      - test`);
  lines.push(`      - build:`);
  if (runLint || runTests) lines.push(`          requires: [test]`);
  const deployLine = requireManualApproval
    ? `      - deploy:\n          requires: [build]\n          type: approval`
    : `      - deploy:\n          requires: [build]`;
  lines.push(deployLine);

  return {
    provider: "circleci",
    filePath: `.circleci/config.yml`,
    content: lines.join("\n") + "\n",
  };
}

// ───────────────────────────────────────────────
// Helper — list the secrets each deploy target requires.
// Useful for the route handler to populate requiredSecrets.
// ───────────────────────────────────────────────

export function requiredSecretsForTarget(target: CloudDeployTargetId): string[] {
  switch (target) {
    case "vercel": return ["VERCEL_TOKEN", "VERCEL_ORG_ID", "VERCEL_PROJECT_ID"];
    case "aws": return ["AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_REGION"];
    case "gcp": return ["GCP_SA_KEY", "GCP_REGION", "GCP_PROJECT_ID"];
    case "supabase": return ["SUPABASE_ACCESS_TOKEN"];
    case "self_hosted": return ["DEPLOY_HOST", "DEPLOY_USER", "DEPLOY_SSH_KEY"];
    default: return [];
  }
}
