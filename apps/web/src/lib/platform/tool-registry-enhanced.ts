// Enhanced tool registry — self-versioning, self-deprecating, self-documenting, self-billing.
//
// The spec (14.2.1): "Every capability is a typed tool with name, description,
// input schema, output schema, side-effect flag, scopes, cost, rate limits, and version."
//
// Enhancements over the base tool-registry.ts:
//   - Self-versioning — tools version with the codebase. Breaking changes → major bump (CI-enforced).
//   - Self-documentation — docs generated from schema + metadata. No hand-written docs.
//   - Self-testing — fixture suites run continuously in the sandbox.
//   - Self-deprecating — zero usage over a rolling window → flagged for removal.
//   - Self-billing — cost per call rolls up to user/ws/agent/region/vertical.
//   - Discovery API — list, search, filter, version query.
//   - Sandbox playground — call any tool with generated sample inputs.
//   - Tool analytics — usage, error rates, latency, cost, deprecation status.

import { db } from "@supa/db";
import { toolRegistry, toolFixtures, toolUsageStats } from "@supa/db/schema";
