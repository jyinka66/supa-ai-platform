/**
 * Generate documentation for a tool from its schema + metadata.
 * No hand-written docs to drift — the docs are always in sync with the code.
 */
export async function generateToolDocs(toolKey: string): Promise<ToolDocumentation | null> {
  const toolRows = await db
    .select()
    .from(toolRegistry)
    .where(eq(toolRegistry.key, toolKey))
    .limit(1);
  const tool = toolRows[0];
  if (!tool) return null;

  // Fetch fixtures for this tool.
  const fixtureRows = await db
    .select({ name: toolFixtures.name, input: toolFixtures.input })
    .from(toolFixtures)
    .where(eq(toolFixtures.toolKey, toolKey))
    .limit(10);

  // Generate sample input from the input schema (stub — a full impl uses a JSON Schema faker).
  const exampleInput = generateSampleInput(tool.inputSchema as Record<string, unknown>);

  return {
    key: tool.key,
    name: tool.name,
    description: tool.description,
    version: tool.version,
    category: tool.category,
    inputSchema: (tool.inputSchema as Record<string, unknown>) ?? {},
    outputSchema: (tool.outputSchema as Record<string, unknown>) ?? {},
    billable: tool.billable,
    pricePerCallUsd: tool.pricePerCallUsd != null ? Number(tool.pricePerCallUsd) : 0,
    rateLimitPerMin: tool.rateLimitPerMin ?? null,
    status: tool.status,
    exampleInput,
    exampleOutput: null, // would be generated by running the tool in the sandbox.
    fixtures: fixtureRows.map((f) => ({ name: f.name, input: (f.input as Record<string, unknown>) ?? {} })),
  };
}

/** Generate a sample input from a JSON Schema (stub). */
export function generateSampleInput(schema: Record<string, unknown>): Record<string, unknown> {
  const properties = schema.properties as Record<string, Record<string, unknown>> | undefined;
  if (!properties) return {};
  const sample: Record<string, unknown> = {};
  for (const [key, prop] of Object.entries(properties)) {
    const type = prop?.type as string | undefined;
    switch (type) {
      case "string": sample[key] = prop?.example ?? "sample"; break;
      case "number": case "integer": sample[key] = prop?.example ?? 0; break;
      case "boolean": sample[key] = prop?.example ?? false; break;
      case "array": sample[key] = []; break;
      case "object": sample[key] = {}; break;
      default: sample[key] = null;
    }
  }
  return sample;
}

// ───────────────────────────────────────────────
// Discovery API — list, search, filter, version query.
// ───────────────────────────────────────────────

export async function searchTools(opts: {
  query?: string;
  category?: string;
  status?: string;
  billable?: boolean;
  limit?: number;
}): Promise<ToolSearchResult[]> {
  const limit = Math.min(opts.limit ?? 50, 200);
  const conditions = [];

  if (opts.query) {
    conditions.push(
      sql`(${toolRegistry.name} ilike ${`%${opts.query}%`} or ${toolRegistry.description} ilike ${`%${opts.query}%`} or ${toolRegistry.key} ilike ${`%${opts.query}%`})`,
    );
  }
  if (opts.category) conditions.push(eq(toolRegistry.category, opts.category));
  if (opts.status) conditions.push(eq(toolRegistry.status, opts.status));
  if (opts.billable !== undefined) conditions.push(eq(toolRegistry.billable, opts.billable));

  const rows = await db
    .select({
      id: toolRegistry.id,
      key: toolRegistry.key,
      name: toolRegistry.name,
      description: toolRegistry.description,
      category: toolRegistry.category,
      version: toolRegistry.version,
      status: toolRegistry.status,
      billable: toolRegistry.billable,
    })
    .from(toolRegistry)
    .where(conditions.length > 0 ? and(...conditions) : undefined)
    .orderBy(toolRegistry.category, toolRegistry.key)
    .limit(limit);

  return rows.map((r) => ({
    id: r.id as string,
    key: r.key,
    name: r.name,
    description: r.description,
    category: r.category,
    version: r.version,
    status: r.status,
    billable: r.billable,
  }));
}

// ───────────────────────────────────────────────
// Self-deprecating — flag tools with zero usage.
// ───────────────────────────────────────────────

const DEPRECATION_WINDOW_DAYS = 90;

/**
 * Find tools with zero usage over the rolling window (90 days).
 * These are flagged for removal — deprecation notices are automatic.
 *
 * Returns the list of zero-usage tools.
 */
export async function findZeroUsageTools(): Promise<Array<{ key: string; name: string; lastUsed: Date | null }>> {
  // Tools that have NO usage stats in the last 90 days.
  const result = await db.execute(sql`
    select t.key, t.name, max(s.period_end) as last_used
    from tool_registry t
    left join tool_usage_stats s
      on s.tool_key = t.key and s.period_end > now() - interval '${DEPRECATION_WINDOW_DAYS} days'
    where t.status = 'active'
    group by t.key, t.name
    having count(s.id) = 0
  `);

  return (result as unknown as Array<{ key: string; name: string; last_used: Date | null }>).map((r) => ({
    key: r.key,
    name: r.name,
    lastUsed: r.last_used ?? null,
  }));
}

/**
 * Auto-deprecate tools with zero usage. Emits deprecation notices.
 * Called by the nightly cron.
 */
export async function autoDeprecateZeroUsageTools(): Promise<{ deprecated: number }> {
  const zeroUsage = await findZeroUsageTools();
  for (const tool of zeroUsage) {
    await db
      .update(toolRegistry)
      .set({ status: "deprecated", deprecatedAt: new Date(), updatedAt: new Date() })
      .where(and(eq(toolRegistry.key, tool.key), eq(toolRegistry.status, "active")));
  }
  return { deprecated: zeroUsage.length };
}

// ───────────────────────────────────────────────
// Tool analytics — usage, error rates, latency, cost.
// ───────────────────────────────────────────────

export async function getToolAnalytics(toolKey: string): Promise<ToolAnalytics | null> {
  const result = await db.execute(sql`
    select
      coalesce(sum(total_calls), 0)::integer as total_calls,
      coalesce(sum(error_count), 0)::integer as error_count,
      avg(avg_latency_ms)::numeric as avg_latency_ms,
      max(p95_latency_ms)::numeric as p95_latency_ms,
      coalesce(sum(total_cost_usd), 0)::numeric as total_cost_usd,
      coalesce(max(unique_callers), 0)::integer as unique_callers
    from tool_usage_stats
    where tool_key = ${toolKey}
      and period_start > now() - interval '30 days'
  `);

  const row = (result as unknown as Array<Record<string, string | number | null>>)[0];
  if (!row) return null;

  const totalCalls = Number(row.total_calls ?? 0);
  const errorCount = Number(row.error_count ?? 0);

  // Get the tool's deprecation status.
  const toolRows = await db.select({ status: toolRegistry.status }).from(toolRegistry).where(eq(toolRegistry.key, toolKey)).limit(1);

  return {
    toolKey,
    totalCalls,
    errorCount,
    errorRate: totalCalls > 0 ? errorCount / totalCalls : 0,
    avgLatencyMs: row.avg_latency_ms != null ? Number(row.avg_latency_ms) : null,
    p95LatencyMs: row.p95_latency_ms != null ? Number(row.p95_latency_ms) : null,
    totalCostUsd: Number(row.total_cost_usd ?? 0),
    uniqueCallers: Number(row.unique_callers ?? 0),
    deprecationStatus: toolRows[0]?.status ?? "unknown",
  };
}

/**
 * Record a tool usage stat (called by callTool after execution).
 * Aggregates into the tool_usage_stats table.
 */
export async function recordToolUsage(input: {
  toolKey: string;
  success: boolean;
  latencyMs: number;
  costUsd: number;
}): Promise<void> {
  const now = new Date();
  const periodStart = new Date(now.getFullYear(), now.getMonth(), now.getDate(), now.getHours());
  const periodEnd = new Date(periodStart.getTime() + 3600000); // 1-hour bucket.

  try {
    await db.execute(sql`
      insert into tool_usage_stats (tool_key, period_start, period_end, total_calls, error_count, avg_latency_ms, total_cost_usd, unique_callers)
      values (${input.toolKey}, ${periodStart}, ${periodEnd}, 1, ${input.success ? 0 : 1}, ${input.latencyMs}, ${input.costUsd}, 1)
      on conflict (tool_key, period_start)
      do update set
        total_calls = tool_usage_stats.total_calls + 1,
        error_count = tool_usage_stats.error_count + ${input.success ? 0 : 1},
        avg_latency_ms = (tool_usage_stats.avg_latency_ms * tool_usage_stats.total_calls + ${input.latencyMs}) / (tool_usage_stats.total_calls + 1),
        total_cost_usd = tool_usage_stats.total_cost_usd + ${input.costUsd}
    `);
  } catch {
    // Usage recording must never fail the tool call.
  }
}

// ───────────────────────────────────────────────
// Self-versioning — CI-enforced major bump on breaking changes.
// ───────────────────────────────────────────────

/**
 * Check if a version bump is valid per semver rules.
 * - Breaking input schema changes → major bump required (e.g. 1.2.0 → 2.0.0).
 * - New optional fields → minor bump (e.g. 1.2.0 → 1.3.0).
 * - Bug fixes → patch bump (e.g. 1.2.0 → 1.2.1).
 *
 * @returns { valid: boolean, requiredBump: 'major'|'minor'|'patch', reason: string }
 */
export function validateVersionBump(
  oldVersion: string,
  newVersion: string,
  oldSchema: Record<string, unknown>,
  newSchema: Record<string, unknown>,
): { valid: boolean; requiredBump: "major" | "minor" | "patch"; reason: string } {
  const oldParts = oldVersion.split(".").map(Number);
  const newParts = newVersion.split(".").map(Number);

  if (oldParts.length !== 3 || newParts.length !== 3) {
    return { valid: false, requiredBump: "patch", reason: "invalid_semver" };
  }

  const [oldMajor, oldMinor, oldPatch] = oldParts as [number, number, number];
  const [newMajor, newMinor, newPatch] = newParts as [number, number, number];

  // Detect breaking changes (removed required fields or changed types).
  const oldRequired = (oldSchema.required as string[] | undefined) ?? [];
  const newRequired = (newSchema.required as string[] | undefined) ?? [];
  const oldProps = (oldSchema.properties as Record<string, Record<string, unknown>>) ?? {};
  const newProps = (newSchema.properties as Record<string, Record<string, unknown>>) ?? {};

  let hasBreaking = false;
  let hasAddition = false;

  // Removed required fields → breaking.
  for (const field of oldRequired) {
    if (!newRequired.includes(field)) {
      hasBreaking = true;
    }
  }

  // Changed types → breaking.
  for (const [key, oldProp] of Object.entries(oldProps)) {
    const newProp = newProps[key];
    if (newProp && oldProp.type !== newProp.type) {
      hasBreaking = true;
    }
  }

  // New fields → addition (minor).
  for (const key of Object.keys(newProps)) {
    if (!oldProps[key]) {
      hasAddition = true;
    }
  }

  if (hasBreaking) {
    const valid = newMajor > oldMajor;
    return { valid, requiredBump: "major", reason: valid ? "breaking_change_major_bump" : "breaking_change_requires_major_bump" };
  }

  if (hasAddition) {
    const valid = newMinor > oldMinor || newMajor > oldMajor;
    return { valid, requiredBump: "minor", reason: valid ? "new_field_minor_bump" : "new_field_requires_minor_bump" };
  }

  const valid = newPatch > oldPatch || newMinor > oldMinor || newMajor > oldMajor;
  return { valid, requiredBump: "patch", reason: valid ? "patch_ok" : "patch_bump_required" };
}
